#[test]
fn wasmtime_smoke_supports_falls_through_bcp47_chain() {
    let Some(h) = SmokeHarness::build_or_skip() else {
        return;
    };
    let (mut store, bindings) = h.instantiate();
    let caps = bindings.stringcheese_icu_case_capabilities();
    // `en-US` is not registered directly, but falls back to `en`.
    let ok = caps
        .call_supports(&mut store, &loc("en-US"))
        .expect("supports trap-free");
    assert!(ok, "en-US should resolve via BCP 47 fallback to en");
    // `ko` is not registered at all.
    let missing = caps
        .call_supports(&mut store, &loc("ko"))
        .expect("supports trap-free");
    assert!(!missing, "ko is not in the bundled pack set");
}
